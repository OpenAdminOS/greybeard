// Repackage the immutable v0.1.0 release core without rebuilding or resigning it.
import { createHash } from 'node:crypto';
import { copyFile, mkdir, readFile, chmod, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
if (process.platform !== 'darwin' || process.arch !== 'arm64') throw new Error('Published Mac packaging requires Apple Silicon.');
const root = resolve(import.meta.dirname, '..');
const directory = join(root, 'dist/published-core');
const output = join(root, 'dist/executable');
await mkdir(directory, { recursive: true }); await mkdir(output, { recursive: true });
const sourceSha = 'd1547bd2ab5741b69e2c32ab623a1a25178c517a';
const archiveHash = '06a553a902458ce660aa17bc7d26a2bb687f70091287c9fbe99ed0ed75a65328';
const coreHash = '873661e746e023c3713c42e99668c62f72be9c665376e983f098aa0d422155ce';
const archive = 'greybeard-darwin-arm64.tar.gz';
const metadataName = 'greybeard-darwin-arm64.metadata.json';
execFileSync('gh', ['release', 'download', 'v0.1.0', '--repo', 'OpenAdminOS/greybeard', '--pattern', archive, '--pattern', metadataName, '--dir', directory], { stdio: 'inherit' });
const hash = data => createHash('sha256').update(data).digest('hex');
const metadata = JSON.parse(await readFile(join(directory, metadataName), 'utf8'));
if (metadata.sourceSha !== sourceSha || metadata.executableSha256 !== coreHash || metadata.sha256 !== archiveHash || metadata.version !== '0.1.0' || metadata.signing.notarized !== true || metadata.signing.teamId !== 'D259ULY2B4' || hash(await readFile(join(directory, archive))) !== archiveHash) throw new Error('Published core provenance does not match the pinned v0.1.0 release.');
const members = execFileSync('tar', ['-tzf', join(directory, archive)], { encoding: 'utf8' }).trim().split(/\r?\n/);
if (members.length !== 1 || members[0] !== 'greybeard') throw new Error('Unexpected published archive contents.');
execFileSync('tar', ['-xzf', join(directory, archive), '-C', directory]);
const core = join(directory, 'greybeard');
if (hash(await readFile(core)) !== coreHash) throw new Error('Published executable hash differs.');
execFileSync('codesign', ['--verify', '--strict', core], { stdio: 'inherit' });
await copyFile(core, join(output, 'greybeard-darwin-arm64'));
await chmod(join(output, 'greybeard-darwin-arm64'), 0o755);
await writeFile(join(output, 'macos-signature.json'), JSON.stringify(metadata.signing, null, 2));
await writeFile(join(output, 'software-source.json'), JSON.stringify({ sourceSha, version: metadata.version, executableSha256: coreHash }, null, 2));
console.log(`Verified immutable v0.1.0 core from ${sourceSha}.`);
